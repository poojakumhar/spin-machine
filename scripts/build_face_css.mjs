// Generates app/face.css: the shading of the three reel faces, built as ONE system.
// Run: node scripts/build_face_css.mjs
// To change the look, edit the numbers in the :root block of app/face.css (no rebuild needed).
// To change the SHAPE of the falloff (stop positions) or the noise strength, edit this file and run it again.
import { writeFileSync } from "node:fs";

const EDGE_X_END = 19;     // % of the width where the side curvature has faded to nothing
const EDGE_Y_END = 16;     // % of the height where the top/bottom curvature has faded to nothing
const N = 16;              // stops per falloff: many stops on an eased curve, so there are no visible steps
const HI_STOPS = 14;
const NOISE_ALPHA = 0.075; // alpha scale of the noise: mean opacity is about half of this, so roughly 3-4%

const ease = (t) => 0.5 * (1 + Math.cos(Math.PI * t));   // cosine curve: 1 at the edge, 0 where the falloff ends, flat at both ends (gentlest possible slope)
const pct = (v) => `${+v.toFixed(2)}%`;
const a = (v, varName) => `rgb(var(--face-edge-rgb) / calc(var(${varName}) * ${v.toFixed(4)}))`;

function falloff(varName, end) {
  const dark = [];
  for (let i = 0; i <= N; i++) { const t = i / N; dark.push(`${a(ease(t), varName)} ${pct(t * end)}`); }
  const light = [];
  for (let i = N; i >= 0; i--) { const t = i / N; light.push(`${a(ease(t), varName)} ${pct(100 - t * end)}`); }
  return [...dark, ...light];
}
const horizontal = `linear-gradient(90deg, ${falloff("--face-edge-x", EDGE_X_END).join(", ")})`;
const vertical = `linear-gradient(180deg, ${falloff("--face-edge-y", EDGE_Y_END).join(", ")})`;
const hiStops = [];
for (let i = 0; i <= HI_STOPS; i++) {
  const t = i / HI_STOPS;
  hiStops.push(`rgb(var(--face-hi-rgb) / calc(var(--face-hi) * ${Math.pow(1 - t, 2.2).toFixed(4)})) ${pct(t * 100)}`);
}
const highlight = `radial-gradient(ellipse var(--face-hi-w) var(--face-hi-h) at var(--face-hi-x) var(--face-hi-y), ${hiStops.join(", ")})`;
const noise = `url("data:image/svg+xml;utf8,<svg xmlns='http://www.w3.org/2000/svg' width='240' height='240'><filter id='n' x='0' y='0' width='100%' height='100%' color-interpolation-filters='sRGB'><feTurbulence type='fractalNoise' baseFrequency='.65' numOctaves='2' seed='7' stitchTiles='stitch'/><feColorMatrix values='0 0 0 0 .91  0 0 0 0 .82  0 0 0 0 .63  ${NOISE_ALPHA} 0 0 0 0'/></filter><rect width='100%' height='100%' filter='url(%23n)'/></svg>")`;

const css = `/* Reel faces. GENERATED by scripts/build_face_css.mjs; the numbers below are meant to be edited by hand.
   One element per reel (.face), the same variables for all three, each shading centred on its own panel.
   Layers, top to bottom: noise (stops banding) -> one soft highlight -> top/bottom curvature -> side curvature -> base cream.
   The words and pictures spin in a separate layer above, so this shading never moves. */
:root {
  --face-base: #f1ddb0;           /* base cream, the same for all three reels */
  --face-edge-rgb: 146 98 48;     /* colour the edges fall off to (brown-tan) */
  --face-edge-x: 0.34;            /* strength of the side curvature, 0 to 1 */
  --face-edge-y: 0.38;            /* strength of the top/bottom curvature, 0 to 1 */
  --face-inset: 0.16;             /* soft inner shadow right next to the rings, 0 to 1 */
  --face-inset-size: 46px;
  --face-rim: 0.42;               /* shadow along the arched rim and next to the rings, 0 to 1 */
  --face-hi-rgb: 255 249 230;     /* highlight colour */
  --face-hi: 0.55;                /* highlight strength, 0 to 1 */
  --face-hi-x: 50%;               /* highlight centre inside each panel */
  --face-hi-y: 45%;
  --face-hi-w: 62%;               /* highlight size (radius) as a share of the panel */
  --face-hi-h: 52%;
}
.face {
  position: absolute;
  z-index: 1;
  pointer-events: none;
  background-color: var(--face-base);
  background-image:
    ${noise},
    ${highlight},
    ${vertical},
    ${horizontal};
  box-shadow: inset 0 0 var(--face-inset-size) rgb(var(--face-edge-rgb) / var(--face-inset));
}
`;
writeFileSync("app/face.css", css);
console.log("wrote app/face.css", css.length, "bytes");
